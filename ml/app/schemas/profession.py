def encode_profession(value):
    normalized = normalize_profession(value)
    canonical = {
        normalize_profession(name): int(code) for code, name in PROFESSION_NAMES.items()
    }
    aliases = {
        normalize_profession(key): canonical[normalize_profession(name)]
        for key, name in PROFESSION_RENAMES.items()
    }
    return canonical.get(normalized, aliases.get(normalized))
